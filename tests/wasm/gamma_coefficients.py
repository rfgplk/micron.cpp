"""Reproduce the coefficients of log Gamma(1+z), |z| <= 1/4."""
import argparse
from pathlib import Path
import mpmath as mp

parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument('--check', action='store_true')
args = parser.parse_args()
mp.mp.prec = 256
rows = ['  ' + mp.nstr((-1)**k * mp.zeta(k)/k, 60) + 'L,' for k in range(2, 65)]
euler_lo = mp.euler - mp.nint(mp.euler * mp.power(2, 113)) * mp.power(2, -113)
text = '''// Copyright (c) 2026- David Lucius Severus
// Distributed under the Boost Software License, Version 1.0.
// See accompanying file LICENSE_1_0.txt or http://www.boost.org/LICENSE_1_0.txt
#pragma once
// Integral of DLMF 5.7.4; regenerated by tests/wasm/gamma_coefficients.py.
namespace micron::wasm::math
{
inline constexpr long double __lgamma_coefficients[]{
''' + '\n'.join(rows) + '\n};\ninline constexpr long double __euler_lo = ' + mp.nstr(euler_lo, 60) + 'L;\n}\n'
path = Path(__file__).resolve().parents[2]/'src/bits/wasm/math/gamma_coefficients.hpp'
if args.check:
    if path.read_text() != text: raise SystemExit('gamma coefficient table differs from its generator')
else: path.write_text(text)
