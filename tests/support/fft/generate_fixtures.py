#!/usr/bin/env python3
"""Regenerate FFT reference samples with mpmath at 256-bit precision."""
from pathlib import Path
import mpmath as mp
mp.mp.prec = 256
lines = ['// Generated by generate_fixtures.py; mpmath precision = 256 bits.', '#pragma once',
         'struct fft_reference { usize n, k; long double real, imag; };', 'inline constexpr fft_reference fft_references[] = {']
for n in (17, 32, 101, 256):
    x = [mp.mpc(mp.mpf(j % 13 - 6)/8, mp.mpf(j % 7 - 3)/16) for j in range(n)]
    for k in (0, 1, 3, n//2, n-1):
        z = sum(x[j] * mp.exp(-2j*mp.pi*j*k/n) for j in range(n))
        def literal(v):
            if abs(v) < mp.mpf('1e-70'): v = mp.mpf(0)
            return mp.nstr(v, 64) + 'L'
        lines.append(f'  {{{n}, {k}, {literal(z.real)}, {literal(z.imag)}}},')
lines.append('};')
Path(__file__).with_name('fixtures.hpp').write_text('\n'.join(lines) + '\n')
