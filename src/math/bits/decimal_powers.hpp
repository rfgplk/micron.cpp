#pragma once

#include "../../types.hpp"

namespace micron::math::__impl
{

template<u32 Factor, u32 Rows, u32 Limbs> struct __decimal_powers {
  u16 offsets[Rows + 1]{};
  u32 limbs[Limbs]{};

  consteval __decimal_powers()
  {
    u32 value[86] = { 1 };
    u32 used = 1, position = 0;
    for ( u32 row = 0; row < Rows; ++row ) {
      offsets[row] = static_cast<u16>(position);
      for ( u32 i = 0; i < used; ++i ) limbs[position++] = value[i];
      if ( row + 1 == Rows ) break;
      u64 carry = 0;
      for ( u32 i = 0; i < used; ++i ) {
        const u64 product = static_cast<u64>(value[i]) * Factor + carry;
        value[i] = static_cast<u32>(product % 1000000000);
        carry = product / 1000000000;
      }
      while ( carry ) {
        value[used++] = static_cast<u32>(carry % 1000000000);
        carry /= 1000000000;
      }
    }
    offsets[Rows] = static_cast<u16>(position);
  }
};

// Packed base-10^9 powers: 16 KiB, generated by integer constant evaluation.
inline constexpr __decimal_powers<1220703125, 83, 3486> __decimal_fives;
inline constexpr __decimal_powers<536870912, 34, 565> __decimal_twos;

};      // namespace micron::math::__impl
