// decimal
using namespace micron::__impl::__dec;

inline constexpr u64
__dec_rounded(const __decimal &v) noexcept
{
  if ( v.point < 0 || v.ndigits == 0 ) return 0;
  if ( v.point > 20 ) return ~0ull;
  const u32 np = static_cast<u32>(v.point);
  u64 n = 0;
  u32 i = 0;
  for ( ; i < np && i < v.ndigits; ++i ) n = n * 10 + v.d[i];
  for ( ; i < np; ++i ) n *= 10;
  if ( __dec_round_up(v, np) ) ++n;
  return n;
}

template<typename T>
inline constexpr void
__dec_load(__decimal &v, const __scan_t<T> &s) noexcept
{
  u32 w = 0;
  bool seen = false;
  i32 point = 0;

  for ( const T *p = s.int_first; p != s.int_last; ++p ) {
    u8 d = static_cast<u8>(__digit_val(*p));
    if ( !seen && d == 0 ) continue;      // leading zeros carry nothing
    seen = true;
    if ( w < __dec_cap )
      v.d[w++] = d;
    else if ( d )
      v.truncated = true;
    ++point;
  }
  for ( const T *p = s.frac_first; p != s.frac_last; ++p ) {
    u8 d = static_cast<u8>(__digit_val(*p));
    if ( !seen && d == 0 ) {
      --point;
      continue;
    }
    seen = true;
    if ( w < __dec_cap )
      v.d[w++] = d;
    else if ( d )
      v.truncated = true;
  }
  v.ndigits = w;
  v.point = point;
  __dec_trim(v);
}

inline constexpr i32
__dec_step(i32 distance) noexcept
{
  return (distance >= static_cast<i32>(sizeof(__powtab))) ? 27 : static_cast<i32>(__powtab[distance]);
}

template<typename F, typename T>
[[gnu::noinline, gnu::cold]] inline constexpr F
__decimal_path(const __scan_t<T> &s) noexcept
{
  using TR = __fmt_traits<F>;
  __decimal v;
  __dec_load(v, s);
  if ( v.ndigits == 0 ) return __zero<F>(s.neg);

  const i64 pt = static_cast<i64>(v.point) + s.exp_lit;
  if ( pt > TR::largest_power + 2 ) return __inf<F>(s.neg);
  if ( pt < TR::smallest_power - 2 ) return __zero<F>(s.neg);
  v.point = static_cast<i32>(pt);

  i32 exp2 = 0;
  while ( v.ndigits != 0 && v.point > 0 ) {
    const i32 n = __dec_step(v.point);
    __dec_shift(v, -n);
    exp2 += n;
  }
  while ( v.ndigits != 0 && (v.point < 0 || (v.point == 0 && v.d[0] < 5)) ) {
    const i32 n = __dec_step(-v.point);
    __dec_shift(v, n);
    exp2 -= n;
  }
  if ( v.ndigits == 0 ) return __zero<F>(s.neg);
  --exp2;      // [0.5, 1) -> [1, 2)

  const i32 bias = TR::min_exponent;
  if ( exp2 < bias + 1 ) {
    const i32 n = bias + 1 - exp2;
    __dec_shift(v, -n);
    exp2 += n;
  }
  if ( exp2 - bias >= TR::infinite_power ) return __inf<F>(s.neg);

  __dec_shift(v, TR::mantissa_bits + 1);
  u64 mant = __dec_rounded(v);
  if ( mant == (2ull << TR::mantissa_bits) ) {      // the rounding carried into a new binade
    mant >>= 1;
    ++exp2;
    if ( exp2 - bias >= TR::infinite_power ) return __inf<F>(s.neg);
  }
  if ( (mant & (1ull << TR::mantissa_bits)) == 0 ) exp2 = bias;      // stayed subnormal

  return __assemble<F>(s.neg, static_cast<u64>(exp2 - bias), mant & ((1ull << TR::mantissa_bits) - 1));
}

//%%%%%%%%%%%%%%%%%%%
// hex

template<typename F>
inline constexpr F
__hex_value(u64 mant, i64 bexp, bool neg, bool sticky) noexcept
{
  using TR = __fmt_traits<F>;
  constexpr i32 mb = TR::mantissa_bits;
  if ( mant == 0 ) return __zero<F>(neg);

  const i32 lz = static_cast<i32>(clz64(mant));
  const u64 w = mant << lz;           // bit 63 set
  const i64 e2 = bexp + 63 - lz;      // value == 1.f * 2^e2
  i64 biased = e2 - TR::min_exponent;

  i32 drop = 63 - mb;
  if ( biased <= 0 ) {      // subnormal
    const i64 extra = 1 - biased;
    if ( extra >= 64 - drop ) return __zero<F>(neg);
    drop += static_cast<i32>(extra);
    biased = 0;
  }

  const u64 rest = w & ((1ull << drop) - 1);
  u64 top = w >> drop;
  const u64 half = 1ull << (drop - 1);

  bool up = false;
  if ( rest > half )
    up = true;
  else if ( rest == half )
    up = sticky || (top & 1) != 0;
  if ( up ) ++top;

  if ( top >= (2ull << mb) ) {
    top >>= 1;
    ++biased;
  }
  if ( biased >= TR::infinite_power ) return __inf<F>(neg);
  if ( biased >= 1 ) top &= ~(1ull << mb);      // at biased == 0 the implicit bit promotes instead
  return __assemble<F>(neg, static_cast<u64>(biased), top);
}

enum class __status : u8 { ok = 0, invalid = 1, out_of_range = 2 };

template<typename F>
inline constexpr __status
__range_of(F v) noexcept
{
  using U = typename math::ieee::traits<F>::uint_type;
  const U u = math::ieee::to_bits(v) & static_cast<U>(~math::ieee::traits<F>::sign_mask);
  if ( u == 0 || u == static_cast<U>(math::ieee::traits<F>::exp_mask) ) return __status::out_of_range;
  return __status::ok;
}

template<typename F, bool Bounded, typename T>
inline constexpr __status
__parse(const T *first, const T *last, F &out, const T *&stop) noexcept
{
  const __scan_t<T> s = __scan<Bounded>(first, last);
  stop = s.stop;

  switch ( s.kind ) {
  case __kind::none:
    out = __zero<F>(false);      // a total failure is +0, as strtod has it
    return __status::invalid;
  case __kind::inf:
    out = __inf<F>(s.neg);
    return __status::ok;
  case __kind::nan:
    out = __nan<F>(s.neg, s.payload);
    return __status::ok;
  case __kind::hex:
    out = __hex_value<F>(s.mant, s.exp10, s.neg, s.truncated);
    return s.mant == 0 ? __status::ok : __range_of(out);
  default:
    break;
  }

  if ( s.mant == 0 ) {      // "0", "0.000", "0e999" and every signed form of them
    out = __zero<F>(s.neg);
    return __status::ok;
  }
  if ( !s.truncated && __exact<F>(s.mant, s.exp10, s.neg, out) ) return __status::ok;

  __am a = __eisel_lemire<F>(s.exp10, s.mant);
  bool punt = (a.power2 < 0);
  if ( !punt && s.truncated ) {
    punt = !(a == __eisel_lemire<F>(s.exp10, s.mant + 1));
  }
  if ( punt )
    out = __decimal_path<F>(s);
  else
    out = __assemble<F>(s.neg, static_cast<u64>(a.power2), a.mantissa);
  return __range_of(out);
}

template<typename F, bool Bounded, typename T>
inline constexpr F
__parse_prefix(const T *first, const T *last) noexcept
{
  F v = static_cast<F>(0);
  const T *stop = nullptr;
  __parse<F, Bounded>(first, last, v, stop);
  return v;
}

