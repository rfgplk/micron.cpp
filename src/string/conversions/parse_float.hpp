// helpers
template<typename T>
inline constexpr bool
__is_digit(T c) noexcept
{
  return static_cast<u32>(static_cast<u32>(c) - static_cast<u32>('0')) <= 9u;
}

template<typename T>
inline constexpr u32
__digit_val(T c) noexcept
{
  return static_cast<u32>(c) - static_cast<u32>('0');
}

template<typename T>
inline constexpr i32
__hex_val(T c) noexcept
{
  u32 v = static_cast<u32>(c);
  if ( v - static_cast<u32>('0') <= 9u ) return static_cast<i32>(v - static_cast<u32>('0'));
  if ( v - static_cast<u32>('a') <= 5u ) return static_cast<i32>(v - static_cast<u32>('a') + 10u);
  if ( v - static_cast<u32>('A') <= 5u ) return static_cast<i32>(v - static_cast<u32>('A') + 10u);
  return -1;
}

// ascii-lowercase, for the inf/nan/infinity words only
template<typename T>
inline constexpr char
__lower(T c) noexcept
{
  u32 v = static_cast<u32>(c);
  return static_cast<char>(v - static_cast<u32>('A') <= 25u ? v + 32u : v);
}

template<bool Bounded, typename T>
inline constexpr bool
__live(const T *p, const T *e) noexcept
{
  if constexpr ( Bounded )
    return p != e;
  else
    return *p != static_cast<T>(0);
}

// scan
enum class __kind : u8 { none = 0, number = 1, hex = 2, inf = 3, nan = 4 };

template<typename T> struct __scan_t {
  u64 mant = 0;                 // significand; for hex, the hex significand
  i64 exp10 = 0;                // total decimal exponent (binary, for hex)
  i64 exp_lit = 0;              // e/E part
  u64 payload = 0;              // nan payload
  const T *stop = nullptr;      // one past the last consumed character
  const T *int_first = nullptr;
  const T *int_last = nullptr;
  const T *frac_first = nullptr;
  const T *frac_last = nullptr;
  bool neg = false;
  bool truncated = false;
  __kind kind = __kind::none;
};

// mant * 10 + 9 must not wrap
constexpr static const u64 __mant_cap = (~0ull - 9ull) / 10ull;
constexpr static const i64 __exp_clamp = 1000000;

template<bool Bounded, typename T>
inline constexpr bool
__scan_hex(const T *&p, const T *e, __scan_t<T> &s) noexcept
{
  const T *save = p;
  p += 2;      // the caller matched "0x"
  u64 mant = 0;
  i64 bexp = 0;
  bool any = false;
  bool truncated = false;

  while ( __live<Bounded>(p, e) ) {
    i32 d = __hex_val(*p);
    if ( d < 0 ) break;
    any = true;
    if ( mant <= (~0ull >> 4) )
      mant = (mant << 4) | static_cast<u64>(d);
    else {
      bexp += 4;
      if ( d ) truncated = true;
    }
    ++p;
  }
  if ( __live<Bounded>(p, e) && *p == static_cast<T>('.') ) {
    ++p;
    while ( __live<Bounded>(p, e) ) {
      i32 d = __hex_val(*p);
      if ( d < 0 ) break;
      any = true;
      if ( mant <= (~0ull >> 4) ) {
        mant = (mant << 4) | static_cast<u64>(d);
        bexp -= 4;
      } else if ( d )
        truncated = true;
      ++p;
    }
  }
  if ( !any ) {      // "0x" with nothing after it is the integer 0 followed by an 'x'
    p = save;
    return false;
  }
  // the binary-exponent part is optional here, as it is for from_chars
  if ( __live<Bounded>(p, e) && (*p == static_cast<T>('p') || *p == static_cast<T>('P')) ) {
    const T *psave = p;
    ++p;
    bool eneg = false;
    if ( __live<Bounded>(p, e) && (*p == static_cast<T>('+') || *p == static_cast<T>('-')) ) {
      eneg = (*p == static_cast<T>('-'));
      ++p;
    }
    if ( !__live<Bounded>(p, e) || !__is_digit(*p) )
      p = psave;
    else {
      i64 v = 0;
      while ( __live<Bounded>(p, e) && __is_digit(*p) ) {
        if ( v < __exp_clamp ) v = v * 10 + static_cast<i64>(__digit_val(*p));
        ++p;
      }
      bexp += eneg ? -v : v;
    }
  }
  s.mant = mant;
  s.exp10 = bexp;
  s.truncated = truncated;
  s.kind = __kind::hex;
  return true;
}

// case insensitive
template<bool Bounded, typename T>
inline constexpr bool
__match_word(const T *&p, const T *e, const char *word) noexcept
{
  const T *q = p;
  for ( const char *w = word; *w; ++w ) {
    if ( !__live<Bounded>(q, e) || __lower(*q) != *w ) return false;
    ++q;
  }
  p = q;
  return true;
}

template<bool Bounded, typename T>
inline constexpr __scan_t<T>
__scan(const T *p, const T *e) noexcept
{
  __scan_t<T> s;
  s.stop = p;

  while ( __live<Bounded>(p, e) && (*p == static_cast<T>(' ') || *p == static_cast<T>('\t')) ) ++p;

  if ( __live<Bounded>(p, e) ) {
    if ( *p == static_cast<T>('-') ) {
      s.neg = true;
      ++p;
    } else if ( *p == static_cast<T>('+') )
      ++p;
  }
  if ( !__live<Bounded>(p, e) ) return s;

  // inf / infinity -- longest match wins
  if ( __lower(*p) == 'i' ) {
    const T *q = p;
    if ( __match_word<Bounded>(q, e, "infinity") ) {
      s.kind = __kind::inf;
      s.stop = q;
      return s;
    }
    q = p;
    if ( __match_word<Bounded>(q, e, "inf") ) {
      s.kind = __kind::inf;
      s.stop = q;
    }
    return s;
  }
  // nan, optionally nan(payload)
  if ( __lower(*p) == 'n' ) {
    const T *q = p;
    if ( !__match_word<Bounded>(q, e, "nan") ) return s;
    s.kind = __kind::nan;
    s.stop = q;
    if ( __live<Bounded>(q, e) && *q == static_cast<T>('(') ) {
      const T *r = q + 1;
      const T *seq = r;
      while ( __live<Bounded>(r, e) && (__is_digit(*r) || static_cast<u32>(__lower(*r) - 'a') <= 25u || *r == static_cast<T>('_')) ) ++r;
      if ( __live<Bounded>(r, e) && *r == static_cast<T>(')') ) {
        const T *d = seq;
        if ( r - d >= 2 && *d == static_cast<T>('0') && (d[1] == static_cast<T>('x') || d[1] == static_cast<T>('X')) ) d += 2;
        u64 pay = 0;
        bool hex = (d != r);
        for ( const T *k = d; k != r; ++k ) {
          const i32 v = __hex_val(*k);
          if ( v < 0 ) {
            hex = false;
            break;
          }
          pay = (pay << 4) | static_cast<u64>(v);
        }
        s.payload = hex ? pay : 0;
        s.stop = r + 1;
      }
    }
    return s;
  }

  // hex float
  if ( *p == static_cast<T>('0') ) {
    const T *q = p + 1;
    if ( __live<Bounded>(q, e) && (*q == static_cast<T>('x') || *q == static_cast<T>('X')) ) {
      const T *h = p;
      if ( __scan_hex<Bounded>(h, e, s) ) {
        s.stop = h;
        return s;
      }
    }
  }

  u64 mant = 0;
  i64 exp10 = 0;
  bool any = false;

  s.int_first = p;
  while ( __live<Bounded>(p, e) && __is_digit(*p) ) {
    u32 d = __digit_val(*p);
    if ( mant <= __mant_cap )
      mant = mant * 10 + d;
    else {
      ++exp10;
      if ( d ) s.truncated = true;
    }
    any = true;
    ++p;
  }
  s.int_last = p;

  s.frac_first = p;
  s.frac_last = p;
  if ( __live<Bounded>(p, e) && *p == static_cast<T>('.') ) {
    ++p;
    s.frac_first = p;
    while ( __live<Bounded>(p, e) && __is_digit(*p) ) {
      u32 d = __digit_val(*p);
      if ( mant <= __mant_cap ) {
        mant = mant * 10 + d;
        --exp10;
      } else if ( d )
        s.truncated = true;
      any = true;
      ++p;
    }
    s.frac_last = p;
  }
  if ( !any ) return s;

  if ( __live<Bounded>(p, e) && (*p == static_cast<T>('e') || *p == static_cast<T>('E')) ) {
    const T *save = p;
    ++p;
    bool eneg = false;
    if ( __live<Bounded>(p, e) && (*p == static_cast<T>('+') || *p == static_cast<T>('-')) ) {
      eneg = (*p == static_cast<T>('-'));
      ++p;
    }
    if ( !__live<Bounded>(p, e) || !__is_digit(*p) )
      p = save;      // "1e" / "1e+"
    else {
      i64 v = 0;
      while ( __live<Bounded>(p, e) && __is_digit(*p) ) {
        if ( v < __exp_clamp ) v = v * 10 + static_cast<i64>(__digit_val(*p));      // clamp, never wrap
        ++p;
      }
      s.exp_lit = eneg ? -v : v;
      exp10 += s.exp_lit;
    }
  }

  if ( exp10 > __exp_clamp ) exp10 = __exp_clamp;
  if ( exp10 < -__exp_clamp ) exp10 = -__exp_clamp;

  s.mant = mant;
  s.exp10 = exp10;
  s.kind = __kind::number;
  s.stop = p;
  return s;
}

