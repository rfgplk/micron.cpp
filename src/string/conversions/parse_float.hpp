// floor(w*T / 2^64) == w*T_hi + floor(w*T_lo / 2^64)
template<i32 BitPrecision>
inline constexpr __fmt_uint128_t
__product(i64 q, u64 w) noexcept
{
  const i32 index = static_cast<i32>(q) - __pow5_128_min;
  __fmt_uint128_t first = umul128(w, __pow5_128[index][1]);
  constexpr u64 precision_mask = (BitPrecision < 64) ? (0xFFFFFFFFFFFFFFFFull >> BitPrecision) : 0xFFFFFFFFFFFFFFFFull;
  if ( (first.hi & precision_mask) == precision_mask ) {
    __fmt_uint128_t second = umul128(w, __pow5_128[index][0]);
    u64 lo = first.lo + second.hi;
    if ( second.hi > lo ) ++first.hi;
    first.lo = lo;
  }
  return first;
}

