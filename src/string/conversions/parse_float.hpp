// %%%%%%%%%%%\%%%%%%%%%%%%
// public fns
// strict range parsers, mirroring try_parse_uint64 / try_parse_int64 in integral.hpp
//
// strict means the whole range must be consumed

template<typename T = char>
inline constexpr bool
try_parse_double(const T *p, usize n, f64 &out)
{
  out = 0.0;
  if ( p == nullptr || n == 0 ) return false;
  const T *stop = nullptr;
  f64 v = 0.0;
  const __impl::__pf::__status st = __impl::__pf::__parse<f64, true>(p, p + n, v, stop);
  if ( st == __impl::__pf::__status::invalid || stop != p + n ) return false;
  out = v;
  return st == __impl::__pf::__status::ok;
}

template<typename T = char>
inline constexpr bool
try_parse_float(const T *p, usize n, f32 &out)
{
  out = 0.0f;
  if ( p == nullptr || n == 0 ) return false;
  const T *stop = nullptr;
  f32 v = 0.0f;
  const __impl::__pf::__status st = __impl::__pf::__parse<f32, true>(p, p + n, v, stop);
  if ( st == __impl::__pf::__status::invalid || stop != p + n ) return false;
  out = v;
  return st == __impl::__pf::__status::ok;
}

template<typename T = char>
inline bool
try_string_to_double(const micron::hstring<T> &buf, f64 &out)
{
  return try_parse_double<T>(buf.cdata(), buf.size(), out);
}

template<typename T = char>
inline bool
try_string_to_float(const micron::hstring<T> &buf, f32 &out)
{
  return try_parse_float<T>(buf.cdata(), buf.size(), out);
}

