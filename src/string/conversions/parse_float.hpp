template<typename F>
inline constexpr F
__assemble(bool neg, u64 biased_exp, u64 mantissa) noexcept
{
  using U = typename math::ieee::traits<F>::uint_type;
  constexpr i32 mb = __fmt_traits<F>::mantissa_bits;
  U u = static_cast<U>(mantissa) | (static_cast<U>(biased_exp) << mb);
  if ( neg ) u |= math::ieee::traits<F>::sign_mask;
  return math::ieee::from_bits<F>(u);
}

template<typename F>
inline constexpr F
__zero(bool neg) noexcept
{
  return __assemble<F>(neg, 0, 0);
}

template<typename F>
inline constexpr F
__inf(bool neg) noexcept
{
  return __assemble<F>(neg, static_cast<u64>(__fmt_traits<F>::infinite_power), 0);
}

template<typename F>
inline constexpr F
__nan(bool neg, u64 payload) noexcept
{
  using U = typename math::ieee::traits<F>::uint_type;
  U m = static_cast<U>(payload) & static_cast<U>(math::ieee::traits<F>::mant_mask);
  m |= static_cast<U>(math::ieee::traits<F>::quiet_nan_bit);
  return __assemble<F>(neg, static_cast<u64>(__fmt_traits<F>::infinite_power), m);
}

template<typename F>
inline constexpr bool
__exact(u64 mant, i64 exp10, bool neg, F &out) noexcept
{
  using TR = __fmt_traits<F>;
  if constexpr ( !__fpu_evaluates_narrow )
    return false;
  else {
    if ( mant > TR::fast_path_max_mantissa ) return false;
    if ( exp10 < -TR::fast_path_max_exp ) return false;

    if ( exp10 > TR::fast_path_max_exp ) {
      if ( exp10 > TR::fast_path_scale_max ) return false;
      const i64 shift = exp10 - TR::fast_path_max_exp;
      if ( mant > TR::fast_path_max_mantissa / __pow10_u64[shift] ) return false;
      mant *= __pow10_u64[shift];
      exp10 = TR::fast_path_max_exp;
    }

    f64 v = static_cast<f64>(mant);
    if ( exp10 > 0 )
      v = v * __pow10_exact[exp10];
    else if ( exp10 < 0 )
      v = v / __pow10_exact[-exp10];
    out = neg ? -static_cast<F>(v) : static_cast<F>(v);
    return true;
  }
}

