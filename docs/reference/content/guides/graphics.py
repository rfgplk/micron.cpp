def section(title, *paragraphs, columns=None, rows=None, bullets=None):
    result = {"title": title, "paragraphs": list(paragraphs)}
    if columns is not None:
        result["table"] = {"columns": columns, "rows": rows}
    if bullets:
        result["bullets"] = bullets
    return result


def entry(name, header, summary, *sections, covers=None):
    result = {"name": name, "header": header, "summary": summary, "sections": list(sections)}
    if covers:
        result["covers"] = covers
    return result


def names(prefix, text):
    return [prefix + name for name in text.split()]


