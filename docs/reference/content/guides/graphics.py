def abi_family(primary, summary, groups, *paragraphs):
    """Group related native records by the operation that consumes them."""
    covered = [name for group, meaning in groups for name in group.split()]
    return entry(V + primary, "gfx/vk/__bits/__vk_types.hpp", summary,
        section("Types and roles", columns=["Types", "Role"], rows=[
            [", ".join("`" + name + "`" for name in group.split()), meaning]
            for group, meaning in groups
        ]),
        section("Requirements and lifetime", *paragraphs),
        covers=names(V, " ".join(name for name in covered if name != primary)),
    )


